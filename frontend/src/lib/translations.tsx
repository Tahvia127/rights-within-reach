const VALID_LANGS: Language[] = ['en', 'es', 'zh', 'tl', 'vi']

// Remember the chosen language across reloads and deep-links so the whole site
// stays in the user's language, not just during one client-side session.
function initialLanguage(): Language {
  try {
    const saved = localStorage.getItem('rwr.lang')
    if (saved && VALID_LANGS.includes(saved as Language)) return saved as Language
  } catch {
    /* localStorage unavailable (private mode) — fall back to English */
  }
  return 'en'
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(initialLanguage)

  const setLanguage = (code: Language) => {
    setLanguageState(code)
    try {
      localStorage.setItem('rwr.lang', code)
    } catch {
      /* ignore persistence failures */
    }
    document.documentElement.lang = code
  }

  useEffect(() => {
    document.documentElement.lang = language
  }, [language])

  const t = (key: string): string => STRINGS[language]?.[key] ?? STRINGS.en[key] ?? key

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  )
}

export function useLanguage() {
  const ctx = useContext(LanguageContext)
  if (!ctx) throw new Error('useLanguage must be used within LanguageProvider')
  return ctx
}